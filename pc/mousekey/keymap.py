"""Windows 虚拟键码 -> HID 用途码。仅覆盖常用按键，缺口在 keymap 末尾注明。"""

# 修饰键位（对应 HID 键盘报告的 modifier 字节）
MOD_LEFT_CTRL = 0x01
MOD_LEFT_SHIFT = 0x02
MOD_LEFT_ALT = 0x04
MOD_LEFT_GUI = 0x08
MOD_RIGHT_CTRL = 0x10
MOD_RIGHT_SHIFT = 0x20
MOD_RIGHT_ALT = 0x40
MOD_RIGHT_GUI = 0x80

VK_MODIFIERS = {
    0x10: MOD_LEFT_SHIFT,
    0x11: MOD_LEFT_CTRL,
    0x12: MOD_LEFT_ALT,
    0x5B: MOD_LEFT_GUI,
    0x5C: MOD_RIGHT_GUI,
    0xA0: MOD_LEFT_SHIFT,
    0xA1: MOD_RIGHT_SHIFT,
    0xA2: MOD_LEFT_CTRL,
    0xA3: MOD_RIGHT_CTRL,
    0xA4: MOD_LEFT_ALT,
    0xA5: MOD_RIGHT_ALT,
}

VK_TO_HID = {
    # 字母
    **{vk: 0x04 + i for i, vk in enumerate(range(0x41, 0x5B))},
    # 数字 1-9、0
    **{vk: 0x1E + i for i, vk in enumerate(range(0x31, 0x3A))},
    0x30: 0x27,
    # 控制键
    0x0D: 0x28,  # Enter
    0x1B: 0x29,  # Esc
    0x08: 0x2A,  # Backspace
    0x09: 0x2B,  # Tab
    0x20: 0x2C,  # Space
    # 符号
    0xBD: 0x2D,  # -
    0xBB: 0x2E,  # =
    0xDB: 0x2F,  # [
    0xDD: 0x30,  # ]
    0xDC: 0x31,  # \
    0xBA: 0x33,  # ;
    0xDE: 0x34,  # '
    0xC0: 0x35,  # `
    0xBC: 0x36,  # ,
    0xBE: 0x37,  # .
    0xBF: 0x38,  # /
    0x14: 0x39,  # CapsLock
    # 功能键
    **{vk: 0x3A + i for i, vk in enumerate(range(0x70, 0x7C))},
    0x2C: 0x46,  # PrintScreen
    0x91: 0x47,  # ScrollLock
    0x13: 0x48,  # Pause
    # 编辑与导航
    0x2D: 0x49,  # Insert
    0x24: 0x4A,  # Home
    0x21: 0x4B,  # PageUp
    0x2E: 0x4C,  # Delete
    0x23: 0x4D,  # End
    0x22: 0x4E,  # PageDown
    0x25: 0x50,  # Left
    0x28: 0x51,  # Down
    0x26: 0x52,  # Up
    0x27: 0x53,  # Right
}

